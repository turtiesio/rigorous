ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def loc(path):
    n, doc = 0, False
    for line in open(os.path.join(ROOT, path)):
        s = line.strip()
        if s.startswith('"""') or s.startswith("'''"):
            if not (s.count('"""') == 2 and len(s) > 3):
                doc = not doc
            continue
        if doc or not s or s.startswith("#"):
            continue
        n += 1
    return n


def table(head, rows):
    print("| " + " | ".join(head) + " |")
    print("|" + "|".join("---" for _ in head) + "|")
    for r in rows:
        print("| " + " | ".join(str(x) for x in r) + " |")
    print()


def ms(f, repeat=5):
    best = float("inf")
    for _ in range(repeat):
        t = time.perf_counter()
        f()
        best = min(best, time.perf_counter() - t)
    return best * 1000


def main():
    print("# Measurements\n")
    print(f"Generated by `python -m bench.measure` on Python {platform.python_version()} ({platform.machine()}). "
          "Timings are best-of-5 wall clock on one machine and are indicative only; "
          "the counts (events, states, nodes) are exact and reproducible.\n")

    print("## 1. Size of what must be trusted\n")
    groups = [("Kernel: events, log, units, composition, runtime", ["rigor/kernel/event.py", "rigor/kernel/unit.py"]),
              ("Reasoners: grounded argumentation, stratified Datalog", ["rigor/kernel/argue.py", "rigor/kernel/datalog.py"]),
              ("Institutional units (authority, ledger, evidence, commitments, adjudication, governance)",
               ["rigor/norms/institution.py", "rigor/norms/ledger.py", "rigor/norms/epistemic.py",
                "rigor/norms/commitments.py", "rigor/norms/adjudicator.py", "rigor/norms/governance.py"]),
              ("Rule set (data, amendable at run time)", ["rigor/norms/org.py"]),
              ("Not trusted for soundness: explorer, impact analysis, adapters, actors, scenario",
               ["rigor/kernel/explore.py", "rigor/impact.py", "rigor/adapters.py", "rigor/actors.py", "rigor/scenario.py", "rigor/synth.py"])]
    table(["Layer", "Lines of code"], [(g, sum(loc(f) for f in fs)) for g, fs in groups])

    print("## 2. Encoding overhead of the end-to-end scenario\n")
    rt, _ = run()
    ext = len(rt.externals())
    size = sum(len(canon(e.payload)) for e in rt.log.events)
    kinds = {}
    for e in rt.log.events:
        k = e.kind.split(".")[0].split("/")[-1]
        kinds[k] = kinds.get(k, 0) + 1
    table(["Quantity", "Value"], [
        ("External stimuli (things a human, clock or adapter did)", ext),
        ("Events recorded in total", len(rt.log.events)),
        ("Derived events per stimulus", f"{(len(rt.log.events) - ext) / ext:.1f}"),
        ("Payload bytes (canonical JSON)", size),
        ("Events by family", ", ".join(f"{k} {v}" for k, v in sorted(kinds.items(), key=lambda kv: -kv[1]))),
    ])

    print("## 3. Cost of revising one claim as the world grows\n")
    print("World: N independent tasks, each a commitment with a receipt and a claim. One probe refutes one task. "
          "\"Nodes re-evaluated\" counts evidence nodes re-labelled plus commitment families re-adjudicated.\n")
    rows = []
    for n in (10, 100, 1000, 5000):
        t = time.perf_counter()
        rt = world_n(n)
        build = (time.perf_counter() - t) * 1000
        epi = next(u for u in rt.root.parts if u.name == "epi")
        adj = next(u for u in rt.root.parts if u.name == "adj")
        w = epi.work + adj.work
        t = time.perf_counter()
        evs = refute(rt, n // 2)
        inc = (time.perf_counter() - t) * 1000
        stim = rt.externals()
        t = time.perf_counter()
        Runtime.replay(make_org(), stim)
        full = (time.perf_counter() - t) * 1000
        rows.append((n, len(rt.log.events), len(evs), epi.work + adj.work - w, f"{inc:.2f}", f"{full:.0f}", f"{full / inc:.0f}x"))
    table(["N tasks", "Log size (events)", "Events caused by the refutation", "Nodes re-evaluated",
           "Incremental (ms)", "Full replay (ms)", "Ratio"], rows)

    print("## 4. Cost of revising a claim at the bottom of a delegation chain\n")
    print("One task delegated through a chain of d commitments; the deepest link is refuted. "
          "Adjudication is per family, so its cost grows with the family, not with the world.\n")
    rows = []
    for d in (1, 5, 20, 50, 100):
        rt = world_n(3, chain=d)
        t = time.perf_counter()
        evs = refute(rt, 1, d - 1)
        rows.append((d, len(evs), sum(1 for e in evs if e.kind == "verdict"), f"{(time.perf_counter() - t) * 1000:.1f}"))
    table(["Chain depth d", "Events caused", "Verdicts issued", "Time (ms)"], rows)

    print("## 5. Global state space versus local reasoning\n")
    print("n independent commitments, each driven by {accepted, refuted} on its own proposition plus a shared clock tick. "
          "Global = states of the composite explored exhaustively. Local = n times the single-commitment state count, "
          "which is all that Theorem T1 (invariants compose) requires checking.\n")

    def make(n):
        def f():
            rt = Runtime(Par(Norms()))
            for i in range(n):
                rt.inject("ok.commit", {"by": f"d{i}", "creditor": "c", "cons": {"prop": f"p{i}"}, "deadline": 2})
            return rt
        return f

    def alpha(n):
        a = [("tick", {"t": 3})]
        for i in range(n):
            a += [("prop.status", {"prop": f"p{i}", "status": "accepted", "since": 1}),
                  ("prop.status", {"prop": f"p{i}", "status": "refuted", "since": None})]
        return a
    one = reach(make(1), alpha(1), 12)["states"]
    rows = []
    for n in (1, 2, 3, 4, 5):
        t = time.perf_counter()
        r = reach(make(n), alpha(n), 30)
        assert r["complete"]
        rows.append((n, r["states"], r["transitions"], f"{(time.perf_counter() - t) * 1000:.0f}", n * one))
    table(["n", "Global states", "Global transitions explored", "Global time (ms)", "Local states to check (n x %d)" % one], rows)

    print("## 6. Interleavings versus partial-order classes\n")
    print("k mutually independent stimuli: k! orderings, all checked to reach one state "
          "(so exploring one would have sufficed). Partial-order reduction is NOT implemented; "
          "this measures what the independence relation would save.\n")
    stim = [("do", {"action": "attest", "args": {"prop": f"P{i}", "pol": "+", "method": "probe"}}, "monitor") for i in range(6)]
    rows = []
    for k in (2, 3, 4, 5, 6):
        t = time.perf_counter()
        finals = interleavings(world, stim[:k])
        rows.append((k, math.factorial(k), len(finals), f"{(time.perf_counter() - t) * 1000:.0f}"))
    table(["k", "Orderings run", "Distinct final states", "Time (ms)"], rows)

    print("## 7. Authority check versus delegation depth\n")
    rows = []
    for depth in (1, 10, 100, 1000):
        rt = Runtime(make_org())
        rt.inject("genesis", genesis(), "constitution")
        cap = "own:alice"
        for i in range(depth):
            evs = rt.do("alice", "delegate", cap=cap, to="alice", actions=["transfer"], scope={"from": "alice"},
                        limits={"credit": 100000 - i}, delegable=True)
            cap = next(e.payload["id"] for e in evs if e.kind == "ok.delegate")
        f = lambda: rt.fork()
        base = ms(f, 3)
        g = lambda: rt.fork().do("alice", "transfer", cap=cap, to="vendor", rtype="credit", amount=1, **{"from": "alice"})
        rows.append((depth, f"{max(ms(g, 3) - base, 0):.3f}"))
    table(["Chain length", "One authorised transfer (ms, fork cost subtracted)"], rows)

    print("## 8. Throughput\n")
    t = time.perf_counter()
    rt = world_n(2000)
    dt = time.perf_counter() - t
    table(["Events processed", "Seconds", "Events per second"], [(len(rt.log.events), f"{dt:.2f}", f"{len(rt.log.events) / dt:.0f}")])


if __name__ == "__main__":
    sys.setrecursionlimit(10000)
    main()
