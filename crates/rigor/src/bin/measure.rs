//! `cargo run --release --bin measure > docs/04-measurements.md`: every number in that document.

use rigor::actors::CREDIT;
use rigor::kernel::explore::{interleavings, reach};
use rigor::kernel::{Cell, Name, Par, Runtime, Unit};
use rigor::model::{About, Act, ActionKind, Amount, Assessment, CapId, Condition, Event, Grant, Method, Offer, Prop, Scope, Time, Version};
use rigor::org::{open_kinds, org};
use rigor::scenario::{attest, delegated, pay, rules, run, world, Cast, ALICE, MONITOR, VENDOR};
use rigor::synth::{refute, world_n, SynthError};
use rigor::units::norms::Norms;
use rigor::world::{Error, World};
use std::collections::BTreeSet;
use std::path::Path;
use std::time::Instant;

#[derive(Debug)]
#[expect(dead_code, reason = "the payloads are read only by the Debug output of a failed run")]
enum Failed {
    World(Error),
    Synth(SynthError),
    Io(std::io::Error),
    Name(rigor::kernel::NameError),
}
impl From<Error> for Failed {
    fn from(e: Error) -> Self {
        Self::World(e)
    }
}
impl From<SynthError> for Failed {
    fn from(e: SynthError) -> Self {
        Self::Synth(e)
    }
}
impl From<rigor::model::Fault> for Failed {
    fn from(e: rigor::model::Fault) -> Self {
        Self::World(Error::Fault(e))
    }
}

fn loc(dir: &Path, files: &[&str]) -> Result<usize, Failed> {
    let mut n = 0;
    for f in files {
        let text = std::fs::read_to_string(dir.join(f)).map_err(Failed::Io)?;
        n += text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with("//")).count();
    }
    Ok(n)
}

fn table(head: &[&str], rows: &[Vec<String>]) {
    println!("| {} |", head.join(" | "));
    println!("|{}|", head.iter().map(|_| "---").collect::<Vec<_>>().join("|"));
    for r in rows {
        println!("| {} |", r.join(" | "));
    }
    println!();
}

/// Best-of-five wall-clock milliseconds.
fn ms<T>(mut f: impl FnMut() -> T) -> f64 {
    let mut best = f64::INFINITY;
    for _ in 0..5 {
        let t = Instant::now();
        let _ = f();
        best = best.min(t.elapsed().as_secs_f64() * 1000.0);
    }
    best
}

fn fact(name: &str) -> Result<Prop, Failed> {
    Ok(Prop::Fact(Name::new(name).map_err(Failed::Name)?))
}

fn main() -> Result<(), Failed> {
    println!("# Measurements\n");
    println!(
        "Generated by `cargo run --release --bin measure` (Rust implementation, release build). Timings are wall clock on one \
         machine and indicative only; the counts (lines, events, states, nodes) are exact and reproducible.\n"
    );

    println!("## 1. Size of what must be trusted\n");
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let layers: [(&str, &[&str]); 5] = [
        ("Kernel: names, log, units, composition, runtime", &["kernel/base.rs", "kernel/log.rs", "kernel/unit.rs", "kernel/runtime.rs", "kernel/mod.rs"]),
        ("Reasoners: grounded argumentation, sorted stratified Datalog", &["logic/argue.rs", "logic/datalog.rs"]),
        ("Typed vocabulary: identifiers, events, acts, rule set", &["model/ids.rs", "model/event.rs", "model/rules.rs"]),
        (
            "Institutional units: authority, ledger, evidence, commitments, adjudication, governance",
            &[
                "units/institution.rs",
                "units/ledger.rs",
                "units/epistemic.rs",
                "units/norms.rs",
                "units/adjudicator.rs",
                "units/governance.rs",
                "units/meter.rs",
            ],
        ),
        (
            "Not trusted for soundness: standard rules, explorer, impact, adapters, actors, scenario, facade",
            &["org.rs", "kernel/explore.rs", "impact.rs", "adapters.rs", "actors.rs", "scenario.rs", "world.rs", "synth.rs"],
        ),
    ];
    let mut rows = Vec::new();
    for (name, files) in layers {
        rows.push(vec![name.to_owned(), loc(&src, files)?.to_string()]);
    }
    table(&["Layer", "Lines of Rust (non-blank, non-comment)"], &rows);

    println!("## 2. Encoding overhead of the end-to-end scenario\n");
    let (w, _) = run(Cast::default(), true, |_| {})?;
    let (events, stimuli) = (w.rt.log().len(), w.rt.stimuli().len());
    let mut bytes = Vec::new();
    let _ = w.rt.log().save(&mut bytes);
    table(
        &["Quantity", "Value"],
        &[
            vec!["External stimuli (things a human, clock or adapter did)".to_owned(), stimuli.to_string()],
            vec!["Events recorded in total".to_owned(), events.to_string()],
            vec![
                "Events recorded per stimulus".to_owned(),
                format!("{:.1}", f64::from(u32::try_from(events).unwrap_or(0)) / f64::from(u32::try_from(stimuli).unwrap_or(1))),
            ],
            vec!["Log size on disk (JSON lines, bytes)".to_owned(), bytes.len().to_string()],
        ],
    );

    println!("## 3. Cost of revising one claim as the world grows\n");
    println!(
        "World: N independent tasks, each a commitment with a receipt and a claim. One probe refutes one task. \
         \"Nodes re-evaluated\" counts evidence nodes re-labelled plus commitment families re-judged.\n"
    );
    let mut rows = Vec::new();
    for n in [10usize, 100, 1000, 5000] {
        let mut w = world_n(n, 1)?;
        let work = |w: &World| -> Result<u64, Error> { Ok(w.epi()?.work.0 + w.adj()?.work.0) };
        let before = work(&w)?;
        let t = Instant::now();
        let caused = refute(&mut w, n / 2, 0)?.len();
        let inc = t.elapsed().as_secs_f64() * 1000.0;
        let nodes = work(&w)? - before;
        let stimuli = w.rt.stimuli();
        let t = Instant::now();
        let _ = Runtime::replay(Box::new(org(Vec::new())?), &stimuli)?;
        let full = t.elapsed().as_secs_f64() * 1000.0;
        rows.push(vec![
            n.to_string(),
            w.rt.log().len().to_string(),
            caused.to_string(),
            nodes.to_string(),
            format!("{inc:.3}"),
            format!("{full:.1}"),
            format!("{:.0}x", full / inc),
        ]);
    }
    table(&["N tasks", "Log size (events)", "Events caused by the refutation", "Nodes re-evaluated", "Incremental (ms)", "Full replay (ms)", "Ratio"], &rows);

    println!("## 4. Cost of revising a claim at the bottom of a delegation chain\n");
    println!("One task delegated through a chain of d commitments; the deepest link is refuted. Adjudication is per family, so its cost grows with the family, not with the world.\n");
    let mut rows = Vec::new();
    for d in [1usize, 5, 20, 50, 100] {
        let mut w = world_n(3, d)?;
        let t = Instant::now();
        let caused = refute(&mut w, 1, d - 1)?;
        let took = t.elapsed().as_secs_f64() * 1000.0;
        let verdicts = caused.iter().filter(|e| matches!(e.event, Event::Verdict(_))).count();
        rows.push(vec![d.to_string(), caused.len().to_string(), verdicts.to_string(), format!("{took:.2}")]);
    }
    table(&["Chain depth d", "Events caused", "Verdicts issued", "Time (ms)"], &rows);

    println!("## 5. Global state space versus local reasoning\n");
    println!(
        "n independent commitments, each driven by {{accepted, refuted}} on its own proposition, plus a shared clock tick. \
         Global = states of the composite, explored exhaustively to a fixed point. Local = n times the single-commitment count, \
         which is all that Theorem T1 (invariants compose) requires checking.\n"
    );
    let env = Name::lit("env");
    let d = rigor::model::ActorId::lit("d");
    let mut single = 0usize;
    let mut rows = Vec::new();
    for n in 1..=6usize {
        let norms: Box<dyn Unit<Event>> = Box::new(Cell(Norms::default()));
        let mut rt: Runtime<Event> = Runtime::new(Box::new(Par::new(vec![norms], &open_kinds())?));
        let mut alphabet = vec![(env.clone(), Event::Tick(Time(3)))];
        for i in 0..n {
            let p = fact(&format!("p{i}"))?;
            let offer =
                Offer { creditor: ALICE, ant: None, cons: Condition::Holds(p.clone()), deadline: Time(2), tags: BTreeSet::new(), parent: None, terms: None };
            let _ = rt.inject(&env, Event::Ok { by: d.clone(), via: CapId::Base(d.clone()), act: Act::Commit(offer) })?;
            for (assessment, since) in [(Assessment::Accepted, Some(Time(1))), (Assessment::Refuted, None)] {
                alphabet.push((
                    env.clone(),
                    Event::Assessed { prop: p.clone(), assessment, since, basis: Vec::new(), was: Assessment::Unsupported, rules: Version(1) },
                ));
            }
        }
        let t = Instant::now();
        let r = reach(&rt, &alphabet, 40, |_, _, _, _| None::<()>)?;
        let took = t.elapsed().as_secs_f64() * 1000.0;
        if n == 1 {
            single = r.states;
        }
        rows.push(vec![n.to_string(), r.states.to_string(), r.transitions.to_string(), format!("{took:.1}"), (n * single).to_string(), r.complete.to_string()]);
    }
    table(&["n", "Global states", "Transitions explored", "Time (ms)", "Local states to check", "Fixed point reached"], &rows);

    println!("## 6. Interleavings versus partial-order classes\n");
    println!(
        "k mutually independent stimuli: k! orderings, all run, all reaching one state (so exploring one would have sufficed). \
         Partial-order reduction is NOT implemented; this measures what the independence relation would save.\n"
    );
    let w = world(Cast::default(), rules())?;
    let mut stimuli = Vec::new();
    for i in 0..7 {
        stimuli.push((MONITOR.0, Event::Do { act: attest(About::Supports(fact(&format!("q{i}"))?), Method::Probe, "x"), cap: None }));
    }
    let mut rows = Vec::new();
    for k in 2..=7usize {
        let t = Instant::now();
        let finals = interleavings(&w.rt, stimuli.get(..k).unwrap_or_default())?;
        let took = t.elapsed().as_secs_f64() * 1000.0;
        rows.push(vec![k.to_string(), (1..=k).product::<usize>().to_string(), finals.len().to_string(), format!("{took:.1}")]);
    }
    table(&["k", "Orderings run", "Distinct final states", "Time (ms)"], &rows);

    println!("## 7. Authority check versus delegation depth\n");
    let mut rows = Vec::new();
    for depth in [1u64, 10, 100, 1000] {
        let mut w = world(Cast::default(), rules())?;
        let mut cap = CapId::Own(ALICE);
        for i in 0..depth {
            let grant = Grant {
                to: ALICE,
                actions: std::iter::once(ActionKind::Transfer).collect(),
                scope: Scope { from: Some(ALICE) },
                limits: std::iter::once((CREDIT, Amount(100_000 - i))).collect(),
                expires: None,
                delegable: true,
            };
            cap = delegated(&w.act_with(&ALICE, &cap, Act::Delegate(grant))?).ok_or(Error::Expected("delegation"))?;
        }
        let fork = ms(|| w.fork());
        let both = ms(|| w.fork().act_with(&ALICE, &cap, pay(ALICE, VENDOR, 1)).map(|e| e.len()));
        rows.push(vec![depth.to_string(), format!("{:.3}", (both - fork).max(0.0))]);
    }
    table(&["Chain length", "One authorised transfer (ms, fork cost subtracted)"], &rows);

    println!("## 8. Throughput\n");
    let t = Instant::now();
    let w = world_n(2000, 1)?;
    let secs = t.elapsed().as_secs_f64();
    let n = w.rt.log().len();
    table(
        &["Events processed", "Seconds", "Events per second"],
        &[vec![n.to_string(), format!("{secs:.2}"), format!("{:.0}", f64::from(u32::try_from(n).unwrap_or(0)) / secs)]],
    );
    Ok(())
}
